import sysconfig, textwrap

code = textwrap.dedent('''
    """Minimal pure-PyTorch replacement for torch_scatter (add/min/max/softmax)."""
    import torch

    def _prep(src, index, dim, dim_size):
        dim = dim % src.dim()
        if index.dim() == 1 and src.dim() > 1:
            shape = [1] * src.dim()
            shape[dim] = -1
            index = index.view(shape).expand_as(src)
        if dim_size is None:
            dim_size = int(index.max()) + 1 if index.numel() > 0 else 0
        out_shape = list(src.shape)
        out_shape[dim] = dim_size
        return dim, index, out_shape, dim_size

    def scatter_add(src, index, dim=-1, out=None, dim_size=None):
        dim, index, shape, _ = _prep(src, index, dim, dim_size)
        if out is None:
            out = torch.zeros(shape, dtype=src.dtype, device=src.device)
        return out.scatter_add_(dim, index, src)

    def _reduce(src, index, dim, out, dim_size, op):
        dim, index, shape, _ = _prep(src, index, dim, dim_size)
        if out is None:
            out = torch.zeros(shape, dtype=src.dtype, device=src.device)
        # empty groups stay 0, matching torch_scatter
        return out.scatter_reduce_(dim, index, src, reduce=op, include_self=False)

    def scatter_max(src, index, dim=-1, out=None, dim_size=None):
        # NOTE: returns (values, None); argmax indices are not computed
        return _reduce(src, index, dim, out, dim_size, "amax"), None

    def scatter_min(src, index, dim=-1, out=None, dim_size=None):
        return _reduce(src, index, dim, out, dim_size, "amin"), None

    def scatter_softmax(src, index, dim=-1, eps=1e-12, dim_size=None):
        dim, index, _, n = _prep(src, index, dim, dim_size)
        mx = scatter_max(src, index, dim, dim_size=n)[0]
        e = (src - mx.gather(dim, index)).exp()
        s = scatter_add(e, index, dim, dim_size=n)
        return e / (s.gather(dim, index) + eps)
''')

